// Generate src/api/taxonomy.gen.ts from server/mirror_api/taxonomy.py (the fixed tag lists).
// The API does not expose the taxonomy yet, so this parses the Python literals directly.
import { readFileSync, writeFileSync } from "node:fs";

const py = readFileSync(new URL("../../server/mirror_api/taxonomy.py", import.meta.url), "utf8");
const strings = (s) => [...s.matchAll(/"([a-z0-9_]+)"/g)].map((m) => m[1]);

function tuple(name) {
  const m = py.match(new RegExp(`^${name}: tuple\\[str, \\.\\.\\.\\] = \\(([\\s\\S]*?)\\)\\n`, "m"));
  if (!m) throw new Error(`taxonomy: ${name} not found`);
  return strings(m[1]);
}
function subcats() {
  const m = py.match(/^SUBCATEGORIES[^=]*= \{([\s\S]*?)\n\}/m);
  if (!m) throw new Error("taxonomy: SUBCATEGORIES not found");
  const out = {};
  for (const e of m[1].matchAll(/"([a-z_]+)": \(([\s\S]*?)\),/g)) out[e[1]] = strings(e[2]);
  return out;
}
function formality() {
  const m = py.match(/^FORMALITY[^=]*= \{([\s\S]*?)\n\}/m);
  const out = {};
  for (const e of m[1].matchAll(/(\d): "([^"]+)"/g)) out[e[1]] = e[2];
  return out;
}
const maxStyle = Number((py.match(/^MAX_STYLE_TAGS = (\d+)/m) || [])[1] || 4);
const data = {
  CATEGORIES: tuple("CATEGORIES"),
  SUBCATEGORIES: subcats(),
  COLORS: tuple("COLORS"),
  PATTERNS: tuple("PATTERNS"),
  MATERIALS: tuple("MATERIALS"),
  SEASONS: tuple("SEASONS"),
  FITS: tuple("FITS"),
  STYLE_TAGS: tuple("STYLE_TAGS"),
  FORMALITY: formality(),
  MAX_STYLE_TAGS: maxStyle,
};
for (const c of data.CATEGORIES) if (!data.SUBCATEGORIES[c]) throw new Error(`no subcategories for ${c}`);
writeFileSync(
  new URL("../src/api/taxonomy.gen.ts", import.meta.url),
  `// Generated by scripts/gen-taxonomy.mjs from server/mirror_api/taxonomy.py. Do not edit.\n` +
    Object.entries(data).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n`).join("\n"),
);
console.log("taxonomy.gen.ts written");
